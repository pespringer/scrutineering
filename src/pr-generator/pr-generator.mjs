import crypto from "node:crypto";

const DEFAULT_MAX_DIFF_LINES = 400;
const DEFAULT_BRANCH_PREFIX = "auto/remediate";

function normalizeMode(mode) {
  return mode === "batched" ? "batched" : "per_repo";
}

function compilePatterns(patterns = []) {
  const compiled = [];
  for (let i = 0; i < patterns.length; i++) {
    const pattern = patterns[i];
    try {
      compiled.push(new RegExp(pattern));
    } catch (error) {
      throw new Error(
        `guardrail regex at index [${i}] is invalid (${pattern}): ${error.message}`,
      );
    }
  }
  return compiled;
}

function matchesAny(filePath, regexes) {
  return regexes.some((regex) => regex.test(filePath));
}

function getRepoFromPath(filePath) {
  const parts = String(filePath || "").split("/");
  if (parts.length >= 2 && parts[0] === "services") {
    return parts[1];
  }
  return "shared";
}

function estimateDiffLines(change) {
  if (Number.isFinite(change?.estimatedDiffLines)) {
    return Math.max(0, Number(change.estimatedDiffLines));
  }

  const actionWeight = change?.action === "base_image_swap" ? 8 : 5;
  return actionWeight;
}

function fingerprintForEnvelope(envelopeSeed) {
  return crypto.createHash("sha256").update(JSON.stringify(envelopeSeed)).digest("hex").slice(0, 16);
}

function groupChangesByRepo(changes) {
  const groups = new Map();
  for (const change of changes) {
    const repo = getRepoFromPath(change?.target?.filePath);
    const current = groups.get(repo) || [];
    current.push(change);
    groups.set(repo, current);
  }

  return groups;
}

function sortChanges(changes) {
  return [...changes].sort((a, b) => {
    const aPath = String(a?.target?.filePath || "");
    const bPath = String(b?.target?.filePath || "");
    if (aPath !== bPath) {
      return aPath.localeCompare(bPath, "en");
    }

    const aPkg = String(a?.target?.packageName || "");
    const bPkg = String(b?.target?.packageName || "");
    if (aPkg !== bPkg) {
      return aPkg.localeCompare(bPkg, "en");
    }

    return String(a?.to || "").localeCompare(String(b?.to || ""), "en");
  });
}

function buildGuardrailResult({ changes, maxDiffLines, allowlistPatterns, denylistPatterns }) {
  const reasons = [];
  let diffTotal = 0;

  for (const change of changes) {
    const filePath = String(change?.target?.filePath || "");
    diffTotal += estimateDiffLines(change);

    if (denylistPatterns.length > 0 && matchesAny(filePath, denylistPatterns)) {
      reasons.push({
        code: "protected_file_denied",
        severity: "error",
        message: `Protected file denied by policy: ${filePath}`,
        filePath,
      });
    }

    if (allowlistPatterns.length > 0 && !matchesAny(filePath, allowlistPatterns)) {
      reasons.push({
        code: "file_not_allowlisted",
        severity: "error",
        message: `File path not allowlisted: ${filePath}`,
        filePath,
      });
    }
  }

  if (diffTotal > maxDiffLines) {
    reasons.push({
      code: "max_diff_exceeded",
      severity: "error",
      message: `Estimated diff lines ${diffTotal} exceed limit ${maxDiffLines}`,
      details: { diffTotal, maxDiffLines },
    });
  }

  return {
    status: reasons.length === 0 ? "pass" : "fail",
    reasonCodes: reasons.map((reason) => reason.code),
    reasons,
    metrics: {
      estimatedDiffLines: diffTotal,
      maxDiffLines,
      touchedFiles: new Set(changes.map((change) => String(change?.target?.filePath || ""))).size,
      totalChanges: changes.length,
    },
  };
}

function buildEnvelope({
  repository,
  changes,
  branchPrefix,
  idempotencyKey,
  executionMode,
  generatedAt,
  runId,
}) {
  const filePaths = changes.map((change) => change?.target?.filePath || "");
  const envelopeSeed = {
    repository,
    idempotencyKey,
    executionMode,
    filePaths,
    changes: changes.map((change) => ({
      target: change.target,
      action: change.action,
      from: change.from,
      to: change.to,
    })),
  };

  const fingerprint = fingerprintForEnvelope(envelopeSeed);
  const shortHash = fingerprint.slice(0, 8);
  const branch = `${branchPrefix}/${repository}/${shortHash}`;

  return {
    artifactType: "pull_request_envelope",
    repository,
    branch,
    title: `chore(security): automated remediation (${repository})`,
    body: [
      "Automated remediation patch generated by pipeline.",
      `- Repository: ${repository}`,
      `- Execution mode: ${executionMode}`,
      `- Idempotency key: ${idempotencyKey}`,
      `- Rollback: git revert <merge_commit_sha>`,
    ].join("\n"),
    labels: ["security", "auto-remediation", executionMode],
    reviewers: ["security-platform"],
    fingerprint,
    idempotencyKey,
    generatedAt,
    runId,
    changes,
    rollback: {
      strategy: "git_revert_commit",
      dryRunCommand: `git revert --no-commit <merge_commit_sha_for_${shortHash}>`,
      verification: "re-run verifier workflow before opening rollback PR",
    },
  };
}

function findExistingEnvelope(previousArtifacts, fingerprint, idempotencyKey) {
  return previousArtifacts.find(
    (artifact) =>
      artifact?.artifactType === "pull_request_envelope" &&
      artifact?.fingerprint === fingerprint &&
      artifact?.idempotencyKey === idempotencyKey,
  );
}

export function createPullRequestArtifacts(input = {}) {
  const executionMode = normalizeMode(input.executionMode);
  const idempotencyKey = String(input.idempotencyKey || "").trim();

  if (!idempotencyKey) {
    return {
      status: "failed",
      error: "invalid_request",
      gate: {
        status: "fail",
        reasonCodes: ["missing_idempotency_key"],
        reasons: [
          {
            code: "missing_idempotency_key",
            severity: "error",
            message: "idempotencyKey is required for PR generation.",
          },
        ],
      },
      pullRequests: [],
      retry: { deduplicated: false },
    };
  }

  const planChanges = Array.isArray(input?.plan?.changes) ? input.plan.changes : [];
  const changes = sortChanges(planChanges);

  const allowlistPatterns = compilePatterns(input.guardrails?.allowlistPaths || []);
  const denylistPatterns = compilePatterns(input.guardrails?.denylistPaths || []);
  const maxDiffLines = Number(input.guardrails?.maxDiffLines || DEFAULT_MAX_DIFF_LINES);

  const gate = buildGuardrailResult({
    changes,
    maxDiffLines,
    allowlistPatterns,
    denylistPatterns,
  });

  if (gate.status !== "pass") {
    return {
      status: "blocked",
      gate,
      pullRequests: [],
      retry: { deduplicated: false },
    };
  }

  const previousArtifacts = Array.isArray(input.previousArtifacts) ? input.previousArtifacts : [];
  const generatedAt = input.generatedAt || new Date().toISOString();
  const runId = input.runId || "local-run";
  const branchPrefix = input.branchPrefix || DEFAULT_BRANCH_PREFIX;

  const grouped =
    executionMode === "batched"
      ? new Map([[input.batchRepository || "staging/remediation-batch", changes]])
      : groupChangesByRepo(changes);

  const pullRequests = [];
  let deduplicatedCount = 0;

  for (const [repository, repoChanges] of grouped.entries()) {
    const seedEnvelope = buildEnvelope({
      repository,
      changes: repoChanges,
      branchPrefix,
      idempotencyKey,
      executionMode,
      generatedAt,
      runId,
    });

    const existing = findExistingEnvelope(previousArtifacts, seedEnvelope.fingerprint, idempotencyKey);
    if (existing) {
      pullRequests.push({
        ...existing,
        deduplicated: true,
      });
      deduplicatedCount += 1;
      continue;
    }

    pullRequests.push({
      ...seedEnvelope,
      deduplicated: false,
    });
  }

  return {
    status: "ready",
    executionMode,
    gate,
    pullRequests,
    retry: {
      deduplicated: deduplicatedCount > 0,
      deduplicatedCount,
      generatedCount: pullRequests.length - deduplicatedCount,
    },
  };
}
